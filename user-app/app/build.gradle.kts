// Supabase config: GitHub Actions Secret (env) অথবা লোকাল local.properties থেকে পড়া হয়।
// কোনো মান না থাকলে অ্যাপ নমুনা ডেটা দিয়ে চলবে।
val localProps = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun secret(name: String): String =
    (System.getenv(name) ?: localProps.getProperty(name) ?: "").trim().replace("\"", "\\\"")

